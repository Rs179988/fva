import { DiscoveredInvariant, StateModel } from './types.js';

export function generateSmtLibProof(model: StateModel, invariants: DiscoveredInvariant[]): string {
  const declarations: string[] = [];

  for (const v of model.stateVariables) {
    const smtType = v.type === 'INT' ? 'Int' : v.type === 'REAL' ? 'Real' : v.type === 'BOOL' ? 'Bool' : '(Array Int Int)';
    declarations.push(`(declare-const ${v.name} ${smtType})`);
    declarations.push(`(declare-const ${v.name}_next ${smtType})`);
  }

  const checks: string[] = [];
  for (const inv of invariants) {
    checks.push(`; --- Invariant: ${inv.id} (${inv.kind}) ---`);
    checks.push(`; Formula: ${inv.formula}`);
    checks.push(`; Prove: NOT(Invariant) is UNSAT (meaning invariant holds universally)`);
  }

  return `; ============================================================================
; Auto-generated by FVA (Formal Verification Anything)
; SMT-LIB 2.0 Theorem Proof for Z3 / CVC5
; Model: ${model.name}
; ============================================================================

(set-logic ALL)
(set-option :produce-models true)

${declarations.join('\n')}

${checks.join('\n')}

(check-sat)
(get-info :all-statistics)
`;
}
